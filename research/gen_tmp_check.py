"""Generate tmp-check.gradle with one JavaExec task per *Check.java harness (Forge + NeoForge)."""
import pathlib
import re

repo = pathlib.Path(__file__).resolve().parents[1]

TEMPLATE = """// AUTO-GENERATED by research/gen_tmp_check.py - one JavaExec per *Check harness
gradle.projectsEvaluated {{
    gradle.rootProject.allprojects {{ p ->
        if (!p.plugins.hasPlugin('java')) return
        def harnesses = [
{entries}
        ]
        harnesses.each {{ e ->
            p.tasks.register(e.key, JavaExec) {{
                it.group = 'verification'
                it.classpath = p.sourceSets.test.runtimeClasspath
                it.mainClass = e.value
                it.jvmArgs '-ea'
            }}
        }}
    }}
}}
"""


def collect(root: pathlib.Path) -> list[tuple[str, str]]:
    entries: list[tuple[str, str]] = []
    for f in sorted(root.rglob("*Check.java")):
        txt = f.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"^package\s+([\w.]+);", txt, re.M)
        if not m:
            continue
        pkg = m.group(1)
        cls = f.stem
        task = "run" + cls
        entries.append((task, f"{pkg}.{cls}"))
    return entries


def write_tree(rel: str) -> list[tuple[str, str]]:
    root = repo / rel / "src/test/java"
    entries = collect(root)
    body = "".join(f"            '{task}': '{fqcn}',\n" for task, fqcn in entries)
    out = repo / rel / "tmp-check.gradle"
    out.write_text(TEMPLATE.format(entries=body), encoding="utf-8")
    return entries


def main() -> None:
    for rel in ("forge/1.19.2", "neoforge/1.21.1"):
        entries = write_tree(rel)
        print(f"{rel}: {len(entries)} harnesses")
        print(" ".join(t for t, _ in entries))


if __name__ == "__main__":
    main()
